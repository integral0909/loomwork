"""A :class:`~loomwork.store.base.Store` that talks to a Loomwork server over HTTP.

Because it implements the exact same contract as :class:`~loomwork.store.memory.MemoryStore`
and the SQL stores, a :class:`~loomwork.worker.worker.Worker` or
:class:`~loomwork.engine.engine.Engine` given an :class:`HttpStore` cannot tell it is
remote: ``Worker(HttpStore(url, token), registry)`` runs workflows against a server exactly
like ``Worker(MemoryStore(), registry)`` runs them embedded.

**Clock rule.** The server always uses its own clock for the "current time" of a request;
this store never sends one. Absolute deadlines that are meaningful data rather than "now"
(a step's retry time, a timer's fire time, a tick's workflow time, ...) are converted to a
duration relative to this store's own clock before being sent, and the server re-anchors
that duration to its own clock on arrival -- see :mod:`loomwork.remote.wire` for the exact
mechanism. This means a client and a server with unsynchronized wall clocks still agree on
every deadline's *meaning* (a lease that expires in 30 seconds), even though they would
disagree about its literal timestamp.

**Notifier.** :attr:`Store.notifier` is local to this process: this store publishes to it
whenever one of its own calls is known to have changed something on the server (a run
was created, a tick committed new steps or timers, a run closed, ...), exactly mirroring
what the embedded stores publish for the same effects. It cannot learn about changes made
by *other* processes -- another worker claiming a step, a signal sent through a different
``HttpStore`` -- that way; long-polling (``long_poll``) is what keeps a remote worker's
latency low for those, by asking the server to hold `claim_tick`/`claim_step` open until
work appears. The notifier on top of that mainly helps several local loops that share one
``HttpStore`` wake each other up without a round trip.
"""

from __future__ import annotations

import asyncio
from collections.abc import Collection, Sequence
from datetime import datetime, timedelta
from typing import Any

import httpx

from loomwork.clock import Clock, SystemClock
from loomwork.codec.payload import Payload
from loomwork.failure import FailureInfo
from loomwork.history.events import Event, StepCompleted, StepFailed, WorkflowStarted
from loomwork.remote import wire
from loomwork.remote.errors import ProblemDetail, exception_for
from loomwork.schedules.model import ScheduleState
from loomwork.store.base import Store
from loomwork.store.notify import TOPIC_STEPS, TOPIC_TICKS, TOPIC_TIMERS, closed_topic, run_topic
from loomwork.store.records import (
    ChildSpec,
    ExecutionRecord,
    ExecutionStatus,
    HeartbeatResult,
    OutboxMessage,
    StepJob,
    TickOutcome,
)
from loomwork.visibility.schema import SearchAttributes

_RETRYABLE_METHODS = frozenset({"GET"})


def _backoff(attempt: int) -> float:
    return min(0.1 * (2.0**attempt), 2.0)


class HttpStore(Store):
    """Store implementation backed by a Loomwork server's worker API.

    Args:
        base_url: the server's origin, for example ``"https://loomwork.internal"``.
        token: a bearer token generated by :func:`loomwork.server.auth.generate_token`.
            Omit only when the server has ``auth.disabled = true``.
        namespace: which of the server's namespaces to use.
        timeout: per-request timeout (seconds), excluding the long-poll wait itself.
        long_poll: how long ``claim_tick``/``claim_step`` ask the server to hold the
            connection open while nothing is ready, capped by the server's own
            ``limits.long_poll_max_seconds``. ``0`` disables long-polling (every claim
            returns immediately), which is what the conformance suite uses so its
            assertions about "nothing to claim" are not timing-dependent.
        max_retries: connection errors and ``5xx`` responses to idempotent (read-only)
            requests are retried with jittered exponential backoff, up to this many
            extra attempts.
        clock: the local clock used to convert deadlines to durations. Defaults to
            :class:`~loomwork.clock.SystemClock`. Tests share a single
            :class:`~loomwork.clock.ManualClock` between this and the server (see
            ``tests/server/test_http_store_conformance.py``) so that offsets round-trip
            to the exact values the test asserts on.
        transport: an ``httpx`` transport override, used by tests to run against an
            in-process ASGI app (``httpx.ASGITransport``) instead of a real socket.
    """

    def __init__(
        self,
        base_url: str,
        token: str | None = None,
        namespace: str = "default",
        *,
        timeout: float = 30.0,
        long_poll: float = 20.0,
        max_retries: int = 3,
        clock: Clock | None = None,
        transport: httpx.AsyncBaseTransport | None = None,
    ) -> None:
        super().__init__()
        if long_poll < 0:
            raise ValueError("long_poll must be >= 0")
        self.base_url = base_url.rstrip("/")
        self.namespace = namespace
        self.token = token
        self.timeout = timeout
        self.long_poll = long_poll
        self.max_retries = max_retries
        self.clock = clock or SystemClock()
        self._transport = transport
        self._client: httpx.AsyncClient | None = None

    # ------------------------------------------------------------------ lifecycle

    async def open(self) -> None:
        if self._client is not None:
            return
        headers = {"Authorization": f"Bearer {self.token}"} if self.token else {}
        self._client = httpx.AsyncClient(
            base_url=f"{self.base_url}/v1/namespaces/{self.namespace}",
            headers=headers,
            timeout=self.timeout,
            transport=self._transport,
        )

    async def close(self) -> None:
        if self._client is not None:
            await self._client.aclose()
            self._client = None

    @property
    def _http(self) -> httpx.AsyncClient:
        if self._client is None:
            raise RuntimeError("HttpStore is not open; call await store.open() first")
        return self._client

    # ------------------------------------------------------------------ transport

    async def _request(
        self,
        method: str,
        path: str,
        *,
        json: dict[str, Any] | None = None,
        params: dict[str, Any] | None = None,
    ) -> dict[str, Any]:
        idempotent = method in _RETRYABLE_METHODS
        attempt = 0
        while True:
            try:
                response = await self._http.request(method, path, json=json, params=params)
            except httpx.TransportError:
                if not idempotent or attempt >= self.max_retries:
                    raise
                await asyncio.sleep(_backoff(attempt))
                attempt += 1
                continue
            if response.status_code >= 500 and idempotent and attempt < self.max_retries:
                await asyncio.sleep(_backoff(attempt))
                attempt += 1
                continue
            if response.status_code >= 400:
                problem = ProblemDetail.from_wire(response.status_code, response.json())
                raise exception_for(problem)
            if response.status_code == 204 or not response.content:
                return {}
            data: dict[str, Any] = response.json()
            return data

    # ------------------------------------------------------------------ executions

    async def create_execution(
        self,
        record: ExecutionRecord,
        started: WorkflowStarted,
        now: datetime,
        extra_inputs: Sequence[Event] = (),
    ) -> tuple[ExecutionRecord, Event]:
        ref = self.clock.now()
        body = {
            "record": wire.execution_record_to_request(record, ref),
            "started": wire.event_to_wire(started),
            "extra_inputs": wire.events_to_wire(list(extra_inputs)),
            "now": wire.offset_seconds(ref, now),
        }
        data = await self._request("POST", "/executions", json=body)
        created = wire.execution_record_from_wire(data["record"])
        event = wire.event_from_wire(data["event"])
        self.notifier.publish(TOPIC_TICKS)
        self.notifier.publish(run_topic(created.run_id))
        return created, event

    async def get_execution(self, run_id: str) -> ExecutionRecord:
        data = await self._request("GET", f"/executions/{run_id}")
        return wire.execution_record_from_wire(data["record"])

    async def find_execution(self, workflow_id: str) -> ExecutionRecord:
        data = await self._request("GET", f"/workflows/{workflow_id}/latest")
        return wire.execution_record_from_wire(data["record"])

    async def list_executions(
        self,
        *,
        workflow_name: str | None = None,
        status: ExecutionStatus | None = None,
        limit: int = 100,
    ) -> list[ExecutionRecord]:
        params: dict[str, Any] = {"limit": limit}
        if workflow_name is not None:
            params["workflow_name"] = workflow_name
        if status is not None:
            params["status"] = status.value
        data = await self._request("GET", "/executions", params=params)
        return [wire.execution_record_from_wire(r) for r in data["records"]]

    # ------------------------------------------------------------------ visibility

    async def query_executions(
        self, query: str, schema: SearchAttributes, now: datetime, limit: int = 100
    ) -> list[ExecutionRecord]:
        ref = self.clock.now()
        body = {
            "query": query,
            "schema": wire.search_attributes_schema_to_wire(schema),
            "now": wire.offset_seconds(ref, now),
            "limit": limit,
        }
        data = await self._request("POST", "/executions/query", json=body)
        return [wire.execution_record_from_wire(r) for r in data["records"]]

    async def get_search_attributes(self, run_id: str) -> dict[str, object]:
        data = await self._request("GET", f"/executions/{run_id}/search-attributes")
        values = wire.search_attributes_values_from_wire(data["attributes"])
        return values or {}

    # ------------------------------------------------------------------ history

    async def load_history(
        self, run_id: str, after_id: int = 0, limit: int | None = None
    ) -> list[Event]:
        params: dict[str, Any] = {"after_id": after_id}
        if limit is not None:
            params["limit"] = limit
        data = await self._request("GET", f"/executions/{run_id}/history", params=params)
        return wire.events_from_wire(data["events"])

    async def append_input(self, run_id: str, event: Event, now: datetime) -> Event | None:
        ref = self.clock.now()
        body = {"event": wire.event_to_wire(event), "now": wire.offset_seconds(ref, now)}
        data = await self._request("POST", f"/executions/{run_id}/inputs", json=body)
        stored = wire.event_opt_from_wire(data.get("event"))
        if stored is not None:
            self.notifier.publish(TOPIC_TICKS)
            self.notifier.publish(run_topic(run_id))
        return stored

    async def request_cancel(self, run_id: str, reason: str, now: datetime) -> bool:
        ref = self.clock.now()
        body = {"reason": reason, "now": wire.offset_seconds(ref, now)}
        data = await self._request("POST", f"/executions/{run_id}/cancel", json=body)
        ok = bool(data["ok"])
        if ok:
            self.notifier.publish(TOPIC_TICKS)
            self.notifier.publish(run_topic(run_id))
        return ok

    async def terminate(self, run_id: str, reason: str, now: datetime) -> bool:
        ref = self.clock.now()
        body = {"reason": reason, "now": wire.offset_seconds(ref, now)}
        data = await self._request("POST", f"/executions/{run_id}/terminate", json=body)
        ok = bool(data["ok"])
        if ok:
            self.notifier.publish(run_topic(run_id))
            self.notifier.publish(closed_topic(run_id))
        return ok

    # ------------------------------------------------------------------ ticks

    async def claim_tick(
        self,
        worker_id: str,
        now: datetime,
        lease: timedelta,
        workflow_names: Collection[str] | None = None,
    ) -> ExecutionRecord | None:
        ref = self.clock.now()
        body = {
            "worker_id": worker_id,
            "now": wire.offset_seconds(ref, now),
            "lease_seconds": lease.total_seconds(),
            "workflow_names": list(workflow_names) if workflow_names is not None else None,
            "wait": self.long_poll,
        }
        data = await self._request("POST", "/ticks/claim", json=body)
        record = data.get("record")
        if record is None:
            return None
        claimed = wire.execution_record_from_wire(record)
        self.notifier.publish(TOPIC_TICKS)
        return claimed

    async def complete_tick(
        self, run_id: str, worker_id: str, outcome: TickOutcome, now: datetime
    ) -> list[Event]:
        ref = self.clock.now()
        body = {
            "worker_id": worker_id,
            "outcome": wire.tick_outcome_to_request(outcome, ref),
            "now": wire.offset_seconds(ref, now),
        }
        data = await self._request("POST", f"/ticks/{run_id}/complete", json=body)
        self.notifier.publish(run_topic(run_id))
        if outcome.new_steps:
            self.notifier.publish(TOPIC_STEPS)
        if outcome.new_timers or outcome.cancel_timers:
            self.notifier.publish(TOPIC_TIMERS)
        if outcome.close is not None:
            self.notifier.publish(closed_topic(run_id))
        return wire.events_from_wire(data["events"])

    async def fail_tick(
        self,
        run_id: str,
        worker_id: str,
        error: str,
        retry_at: datetime,
        now: datetime,
    ) -> None:
        ref = self.clock.now()
        body = {
            "worker_id": worker_id,
            "error": error,
            "retry_at": wire.offset_seconds(ref, retry_at),
            "now": wire.offset_seconds(ref, now),
        }
        await self._request("POST", f"/ticks/{run_id}/fail", json=body)

    # ------------------------------------------------------------------ steps

    async def claim_step(
        self,
        worker_id: str,
        now: datetime,
        lease: timedelta,
        step_names: Collection[str] | None = None,
        queues: Collection[str] | None = None,
    ) -> StepJob | None:
        ref = self.clock.now()
        body = {
            "worker_id": worker_id,
            "now": wire.offset_seconds(ref, now),
            "lease_seconds": lease.total_seconds(),
            "step_names": list(step_names) if step_names is not None else None,
            "queues": list(queues) if queues is not None else None,
            "wait": self.long_poll,
        }
        data = await self._request("POST", "/steps/claim", json=body)
        job = data.get("job")
        if job is None:
            return None
        claimed = wire.step_job_from_wire(job)
        self.notifier.publish(TOPIC_STEPS)
        return claimed

    async def finish_step(
        self,
        job_id: str,
        worker_id: str,
        event: StepCompleted | StepFailed,
        now: datetime,
    ) -> bool:
        ref = self.clock.now()
        body = {
            "worker_id": worker_id,
            "event": wire.event_to_wire(event),
            "now": wire.offset_seconds(ref, now),
        }
        data = await self._request("POST", f"/steps/{job_id}/finish", json=body)
        ok = bool(data["ok"])
        if ok:
            self.notifier.publish(TOPIC_TICKS)
        return ok

    async def retry_step(
        self,
        job_id: str,
        worker_id: str,
        ready_at: datetime,
        failure: FailureInfo,
        now: datetime,
    ) -> bool:
        ref = self.clock.now()
        body = {
            "worker_id": worker_id,
            "ready_at": wire.offset_seconds(ref, ready_at),
            "failure": wire.failure_to_wire(failure),
            "now": wire.offset_seconds(ref, now),
        }
        data = await self._request("POST", f"/steps/{job_id}/retry", json=body)
        ok = bool(data["ok"])
        if ok:
            self.notifier.publish(TOPIC_STEPS)
        return ok

    async def renew_step_lease(self, job_id: str, worker_id: str, expires_at: datetime) -> bool:
        ref = self.clock.now()
        body = {"worker_id": worker_id, "expires_at": wire.offset_seconds(ref, expires_at)}
        data = await self._request("POST", f"/steps/{job_id}/lease", json=body)
        return bool(data["ok"])

    async def heartbeat_step(
        self,
        job_id: str,
        worker_id: str,
        expires_at: datetime,
        details: Payload | None,
        now: datetime,
    ) -> HeartbeatResult | None:
        ref = self.clock.now()
        body = {
            "worker_id": worker_id,
            "expires_at": wire.offset_seconds(ref, expires_at),
            "details": wire.payload_opt_to_wire(details),
            "now": wire.offset_seconds(ref, now),
        }
        data = await self._request("POST", f"/steps/{job_id}/heartbeat", json=body)
        result = data.get("result")
        return None if result is None else wire.heartbeat_result_from_wire(result)

    async def release_step(
        self, job_id: str, worker_id: str, now: datetime, *, consume_attempt: bool
    ) -> bool:
        ref = self.clock.now()
        body = {
            "worker_id": worker_id,
            "now": wire.offset_seconds(ref, now),
            "consume_attempt": consume_attempt,
        }
        data = await self._request("POST", f"/steps/{job_id}/release", json=body)
        ok = bool(data["ok"])
        if ok:
            self.notifier.publish(TOPIC_STEPS)
        return ok

    async def next_step_ready_at(
        self,
        step_names: Collection[str] | None = None,
        queues: Collection[str] | None = None,
    ) -> datetime | None:
        body = {
            "step_names": list(step_names) if step_names is not None else None,
            "queues": list(queues) if queues is not None else None,
        }
        data = await self._request("POST", "/steps/next-ready-at", json=body)
        return wire.iso_decode_opt(data.get("ready_at"))

    async def get_step_jobs(self, run_id: str) -> list[StepJob]:
        data = await self._request("GET", f"/executions/{run_id}/steps")
        return wire.step_jobs_from_wire(data["jobs"])

    # ------------------------------------------------------------------ outbox

    async def relay_outbox(self, now: datetime, limit: int = 100) -> int:
        ref = self.clock.now()
        body = {"now": wire.offset_seconds(ref, now), "limit": limit}
        data = await self._request("POST", "/outbox/relay", json=body)
        processed = int(data["processed"])
        if processed:
            self.notifier.publish(TOPIC_TICKS)
        return processed

    async def outbox_size(self) -> int:
        data = await self._request("GET", "/outbox/size")
        return int(data["size"])

    async def list_children(self, run_id: str) -> list[ExecutionRecord]:
        data = await self._request("GET", f"/executions/{run_id}/children")
        return [wire.execution_record_from_wire(c) for c in data["children"]]

    # ------------------------------------------------------------------ retention

    async def delete_closed_before(self, cutoff: datetime, limit: int = 1000) -> int:
        ref = self.clock.now()
        body = {"cutoff": wire.offset_seconds(ref, cutoff), "limit": limit}
        data = await self._request("POST", "/retention/delete-closed", json=body)
        return int(data["deleted"])

    # ------------------------------------------------------------------ timers

    async def next_timer_at(self) -> datetime | None:
        data = await self._request("GET", "/timers/next")
        return wire.iso_decode_opt(data.get("fire_at"))

    async def fire_due_timers(self, now: datetime, limit: int = 100) -> int:
        ref = self.clock.now()
        body = {"now": wire.offset_seconds(ref, now), "limit": limit}
        data = await self._request("POST", "/timers/fire", json=body)
        fired = int(data["fired"])
        if fired:
            self.notifier.publish(TOPIC_TICKS)
        return fired

    # ------------------------------------------------------------------ schedules

    async def create_schedule(self, state: ScheduleState, now: datetime) -> ScheduleState:
        ref = self.clock.now()
        body = {
            "state": wire.schedule_state_to_request(state, ref),
            "now": wire.offset_seconds(ref, now),
        }
        data = await self._request("POST", "/schedules", json=body)
        return wire.schedule_state_from_wire(data["state"])

    async def get_schedule(self, schedule_id: str) -> ScheduleState:
        data = await self._request("GET", f"/schedules/{schedule_id}")
        return wire.schedule_state_from_wire(data["state"])

    async def list_schedules(self, limit: int = 100) -> list[ScheduleState]:
        data = await self._request("GET", "/schedules", params={"limit": limit})
        return [wire.schedule_state_from_wire(s) for s in data["states"]]

    async def update_schedule(
        self, state: ScheduleState, expected_version: int, now: datetime
    ) -> ScheduleState:
        ref = self.clock.now()
        body = {
            "state": wire.schedule_state_to_request(state, ref),
            "expected_version": expected_version,
            "now": wire.offset_seconds(ref, now),
        }
        data = await self._request("POST", f"/schedules/{state.schedule_id}/update", json=body)
        return wire.schedule_state_from_wire(data["state"])

    async def delete_schedule(self, schedule_id: str) -> bool:
        data = await self._request("POST", f"/schedules/{schedule_id}/delete")
        return bool(data["ok"])

    async def due_schedules(self, now: datetime, limit: int = 100) -> list[ScheduleState]:
        ref = self.clock.now()
        body = {"now": wire.offset_seconds(ref, now), "limit": limit}
        data = await self._request("POST", "/schedules/due", json=body)
        return [wire.schedule_state_from_wire(s) for s in data["states"]]

    async def fire_schedule(
        self,
        state: ScheduleState,
        expected_version: int,
        starts: Sequence[ChildSpec],
        outbox: Sequence[OutboxMessage],
        now: datetime,
    ) -> ScheduleState:
        ref = self.clock.now()
        body = {
            "state": wire.schedule_state_to_request(state, ref),
            "expected_version": expected_version,
            "starts": [wire.child_spec_to_request(c, ref) for c in starts],
            "outbox": [wire.outbox_message_to_request(m) for m in outbox],
            "now": wire.offset_seconds(ref, now),
        }
        data = await self._request("POST", f"/schedules/{state.schedule_id}/fire", json=body)
        return wire.schedule_state_from_wire(data["state"])

    async def next_schedule_at(self) -> datetime | None:
        data = await self._request("GET", "/schedules/next")
        return wire.iso_decode_opt(data.get("fire_at"))
